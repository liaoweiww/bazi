def seed_categories(conn):
    c = conn.cursor()
    for cat in CATEGORIES:
        c.execute(
            'INSERT OR REPLACE INTO material_category (id, name, sort_order) VALUES (?, ?, ?)',
            cat
        )
    c.execute('INSERT OR REPLACE INTO material_category (id, name, sort_order) VALUES (?, ?, ?)',
              (7, '其他', 7))
    conn.commit()


def seed_materials(conn):
    c = conn.cursor()
    for m in MATERIALS:
        name, cat_id, unit, min_p, max_p, last_p = m
        c.execute('''
            INSERT OR IGNORE INTO material_library
                (material_name, category_id, default_unit, market_min_price, market_max_price, last_user_price)
            VALUES (?, ?, ?, ?, ?, ?)
        ''', (name, cat_id, unit, min_p, max_p, last_p))
    conn.commit()


def seed_recipes(conn):
    c = conn.cursor()
    for recipe in RECIPES:
        icon = f"/images/icon-{recipe['name']}.png"
        cover = f"/images/cover-{recipe['name']}.png"
        c.execute('''
            INSERT INTO recipe (name, category, cook_time, difficulty, base_person,
                main_material, main_weight, main_unit, icon_image, cover_image)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ''', (
            recipe['name'], recipe['category'], recipe['cook_time'],
            recipe['difficulty'], recipe['base_person'],
            recipe['main_material'], recipe['main_weight'], recipe['main_unit'],
            icon, cover
        ))
        recipe_id = c.lastrowid

        for i, ing in enumerate(recipe['ingredients']):
            name, amount, unit, price = ing
            c.execute('''
                INSERT INTO recipe_ingredient (recipe_id, material_name, base_amount, unit, price_per_unit, sort_order)
                VALUES (?, ?, ?, ?, ?, ?)
            ''', (recipe_id, name, amount, unit, price, i))

        for i, step in enumerate(recipe['steps']):
            c.execute('''
                INSERT INTO recipe_step (recipe_id, sort_order, content)
                VALUES (?, ?, ?)
            ''', (recipe_id, i + 1, step))

    conn.commit()


def seed_market_data(conn):
    """生成最近30天的模拟市场行情数据"""
    c = conn.cursor()
    import random
    random.seed(42)

    materials = c.execute('SELECT material_name, market_min_price, market_max_price FROM material_library').fetchall()

    for m in materials:
        name, min_p, max_p = m
        mid = (min_p + max_p) / 2
        for day_offset in range(30):
            # 在合理范围内波动 ±15%
            price = round(mid * (1 + random.uniform(-0.15, 0.15)), 2)
            c.execute('''
                INSERT INTO market_price_data (material_name, price, record_date)
                VALUES (?, ?, date('now', 'localtime', '-' || ? || ' days'))
            ''', (name, price, day_offset))

    conn.commit()


def seed_all():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    try:
        seed_categories(conn)
        seed_materials(conn)
        seed_recipes(conn)
        seed_market_data(conn)
        conn.commit()
        print("Seed data loaded successfully!")
        print(f"  - {len(CATEGORIES)} categories")
        print(f"  - {len(MATERIALS)} materials")
        print(f"  - {len(RECIPES)} recipes")
        print(f"  - 30 days market price data")
    finally:
        conn.close()


