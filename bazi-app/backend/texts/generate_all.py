# =================== BUILD ZHUJIE ====================

def build_zhujie():
    stems = list("甲乙丙丁戊己庚辛壬癸")
    branches = list("子丑寅卯辰巳午未申酉戌亥")
    pillars = [
        ("year_pillar", gen_year),
        ("month_pillar", gen_month),
        ("day_pillar", gen_day),
        ("hour_pillar", gen_hour),
    ]
    result = {}
    for pname, pfunc in pillars:
        result[pname] = {}
        for stem in stems:
            result[pname][stem] = {}
            for branch in branches:
                result[pname][stem][branch] = pfunc(stem, branch)
    return result

