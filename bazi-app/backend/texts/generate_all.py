# =================== SHISHEN CALCULATION ====================

def get_ss(stem, other):
    """Get shishen name for 'other' stem relative to 'stem'"""
    wx_s = STEM_WX[stem]; wx_o = STEM_WX[other]
    is_yin = lambda g: g in "乙丁己辛癸"
    same = (is_yin(stem) == is_yin(other))
    if wx_s == wx_o: return "比肩" if same else "劫财"
    # 生: M->F->E->M->W->M (木火土金水)
    gen_me = {"木":"水","火":"木","土":"火","金":"土","水":"金"}
    i_gen = {"木":"火","火":"土","土":"金","金":"水","水":"木"}
    i_ctrl = {"木":"土","火":"金","土":"水","金":"木","水":"火"}
    ctrl_me = {"木":"金","火":"水","土":"木","金":"火","水":"土"}
    if gen_me[wx_s] == wx_o: return "偏印" if same else "正印"
    if i_gen[wx_s] == wx_o: return "食神" if same else "伤官"
    if i_ctrl[wx_s] == wx_o: return "偏财" if same else "正财"
    return "偏官" if same else "正官"

def branch_ss(stem, branch):
    """Get primary shishen and full hidden-stem description"""
    h = BRANCH_HIDDEN[branch]
    main = get_ss(stem, h[0])
    desc = "、".join(f"{s}({get_ss(stem,s)})" for s in h)
    return main, desc

