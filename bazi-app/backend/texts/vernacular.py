def generate_vernacular(paipan_result: dict) -> dict:
    """生成白话解读报告"""
    p = paipan_result.get('four_pillars', {})
    dm = paipan_result.get('day_master', '')
    dm_wx = paipan_result.get('day_master_wuxing', '')
    strength = paipan_result.get('strength', {})
    geju = paipan_result.get('geju', {})
    yongji = paipan_result.get('yongji', {})
    shensha = paipan_result.get('shensha', {})
    cs = paipan_result.get('changsheng', {})
    wxs = paipan_result.get('wuxing_season', {})

    result = {}

    # 1. 日主概述
    personality = WX_PERSONALITY.get(dm_wx, f'日主为{dm_wx}，个性鲜明。')
    sl = strength.get('level', '中和')
    sl_desc = {'身强':'精力充沛，能担大任，适合领导型工作，做事主动积极。',
               '偏强':'比较有主见，做事有魄力，能独立完成任务。','中和':'性格平衡，能进能退，适应能力强。',
               '偏弱':'心思细腻，做事谨慎，需要多借助外力发展。','身弱':'性格温和，善解人意，适合合作型工作。'}.get(sl, '')
    result['日主概述'] = f'您的日主是{dm}（{dm_wx}），{personality}综合判断为{sl}。{sl_desc}'

    # 2. 四柱逐柱解读
    result['四柱解读'] = {}
    pillar_names = {'year':'年柱','month':'月柱','day':'日柱','hour':'时柱'}
    for pk, label in pillar_names.items():
        pl = p.get(pk, {})
        gan, zhi, shishen = pl.get('gan',''), pl.get('zhi',''), pl.get('shishen','')
        nayin = pl.get('nayin','')
        canggan = '、'.join(pl.get('canggan', []))

        parts = [f'{gan}属{dm_wx if pk=="day" else ({"甲":"木","乙":"木","丙":"火","丁":"火","戊":"土","己":"土","庚":"金","辛":"金","壬":"水","癸":"水"}.get(gan,""))}']

        if pk == 'year': parts.append(f'代表祖辈和早年运势，{nayin}命')
        elif pk == 'month': parts.append(f'代表父母和事业根基，{nayin}命')
        elif pk == 'day': parts.append(f'代表您自己和配偶，{nayin}命，坐{zhi}（藏{canggan}）')
        elif pk == 'hour': parts.append(f'代表子女和晚年运势，{nayin}命')

        if shishen and pk != 'day':
            parts.append(f'十神为{shishen}')
            if shishen in SHISHEN_V:
                parts.append(SHISHEN_V[shishen][:60])

        # 十二长生
        cs_info = cs.get(pk, {})
        if cs_info.get('state'):
            st = cs_info['state']
            parts.append(f'日主在此柱处于"{st}"状态')
            if st in CHANGSHENG_V:
                parts.append(CHANGSHENG_V[st])

        result['四柱解读'][label] = '。'.join(parts) + '。'

    # 3. 格局解读
    gj_name = geju.get('name', '')
    gj_text = GEJU_V.get(gj_name, f'格局为{gj_name}，有独特的人生轨迹。')
    result['格局解读'] = gj_text

    # 4. 喜用神建议
    ys = yongji.get('yong_sen', yongji.get('yong_shen', []))
    js = yongji.get('ji_shen', [])
    if ys:
        y_names = '、'.join(f'{y["wuxing"]}({y.get("shishen","")})' for y in ys)
        result['喜用神建议'] = f'对您有利的五行是{y_names}。日常生活中可以多接触这些五行属性的事物来增强运势。比如穿对应颜色的衣服，家中摆放相关的装饰品，或者选择与这些五行相关的行业。'
    if js:
        j_names = '、'.join(f'{j["wuxing"]}({j.get("shishen","")})' for j in js)
        result['忌神提醒'] = f'需要注意的五行是{j_names}。这些方面容易给您带来压力和挑战，需要多加留意，避免因这些因素带来损失。'

    # 5. 神煞解读
    if shensha:
        ss_texts = []
        for name, items in list(shensha.items())[:8]:
            if name in SHENSHA_V:
                locations = ','.join(f'{it["pillar"]}柱' for it in items)
                ss_texts.append(f'{name}（{locations}）：{SHENSHA_V[name]}')
        if ss_texts:
            result['神煞解读'] = '；'.join(ss_texts) + '。'

    # 6. 调候建议
    if yongji.get('tiao_hou'):
        result['调候建议'] = yongji['tiao_hou']

    # 7. 大运提示
    dayun = paipan_result.get('dayun', {})
    cur_dy = dayun.get('current_dayun', {})
    if cur_dy and cur_dy.get('ganzhi'):
        result['当前大运提示'] = f'您目前正行{cur_dy["ganzhi"]}大运（{cur_dy.get("age_range","")}岁），纳音{cur_dy.get("nayin","")}。这十年是您人生的一个重要阶段，把握好这个时期的机遇对后续发展至关重要。'

    result['综合建议'] = f'总的来说，您是{dm}（{dm_wx}）日主，{gj_name}，喜{",".join(y["wuxing"] for y in ys) if ys else "中和"}。建议顺势而为，发挥优势，规避弱势。命理仅供参考，人生真正的高度取决于您的选择和努力。'

    return result
