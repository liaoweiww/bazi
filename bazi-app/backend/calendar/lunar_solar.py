def _get_lunar_data(year):
    """获取指定年份的农历编码数据，返回 (year, leap_month, bitmask, offset)。"""
    if year < 1900 or year > 2100:
        raise ValueError(f"年份 {year} 不在支持范围内 (1900-2100)")
    y, leap, mask, off = LUNAR_DATA[year - 1900]
    return leap, mask, off


def get_lunar_new_year(year):
    """
    返回指定年份的农历正月初一对应的公历日期。

    参数:
        year: 农历年份

    返回:
        date 对象
    """
    _, _, offset = _get_lunar_data(year)
    return date(year, 1, 1) + timedelta(days=offset)


def is_lunar_leap_year(year):
    """
    判断指定农历年是否有闰月。

    参数:
        year: 农历年份

    返回:
        bool: True 表示该年有闰月, False 表示无闰月
    """
    leap, _, _ = _get_lunar_data(year)
    return leap != 0


def get_lunar_month_days(year, month, leap=False):
    """
    获取指定农历月份的天数。

    大月30天, 小月29天。

    参数:
        year: 农历年份
        month: 农历月份 (1-12)
        leap: 是否为闰月

    返回:
        int: 该月天数 (29 或 30)

    异常:
        ValueError: 月份无效或不存在该闰月
    """
    leap_month, bitmask, _ = _get_lunar_data(year)

    if leap:
        if leap_month == 0 or month != leap_month:
            raise ValueError(f"{year}年无闰{month}月 (闰月为{leap_month}月)")
        # 闰月大小在 bit 12
        if bitmask & (1 << 12):
            return 30
        else:
            return 29
    else:
        if month < 1 or month > 12:
            raise ValueError(f"农历月份必须在1-12之间, 收到{month}")
        if bitmask & (1 << (month - 1)):
            return 30
        else:
            return 29


def get_lunar_year_months(year):
    """
    获取指定农历年份的所有月份信息。

    参数:
        year: 农历年份

    返回:
        list of dict: 每月信息
            - month: 月份编号 (1-12)
            - days: 该月天数
            - is_leap: 是否为闰月
    按实际月份顺序排列（闰月紧跟其对应月份之后）
    """
    leap_month, bitmask, _ = _get_lunar_data(year)
    months = []

    for m in range(1, 13):
        # 正常月份
        days = 30 if (bitmask & (1 << (m - 1))) else 29
        months.append({"month": m, "days": days, "is_leap": False})

        # 如果该月后有闰月
        if leap_month == m:
            leap_days = 30 if (bitmask & (1 << 12)) else 29
            months.append({"month": m, "days": leap_days, "is_leap": True})

    return months


def get_lunar_year_days(year):
    """
    获取指定农历年份的总天数。

    平年约354天, 闰年约384天。

    参数:
        year: 农历年份

    返回:
        int: 该农历年的总天数
    """
    leap_month, bitmask, _ = _get_lunar_data(year)
    total = 0

    for m in range(1, 13):
        total += 30 if (bitmask & (1 << (m - 1))) else 29

    if leap_month > 0:
        total += 30 if (bitmask & (1 << 12)) else 29

    return total


def _days_between_dates(d1, d2):
    """计算两个 date 对象之间的天数 (d2 - d1)。"""
    return (d2 - d1).days


def solar_to_lunar(year, month, day):
    """
    公历转农历。

    参数:
        year: 公历年
        month: 公历月 (1-12)
        day: 公历日

    返回:
        dict:
            {
                "lunar_year": int,         # 农历年
                "lunar_month": int,        # 农历月 (1-12)
                "lunar_day": int,          # 农历日 (1-30)
                "is_leap": bool,           # 是否为闰月
                "leap_month": int,         # 该年闰月编号 (0=无闰)
                "year_ganzhi": str,        # 年干支 (以立春为界)
                "month_ganzhi": str,       # 月干支 (以节气为界)
                "day_ganzhi": str,         # 日干支
                "animal": str,             # 生肖
                "solar_term_info": dict,   # 当前所处节气区间
            }

    算法:
        1. 找到目标日期所在的农历年（正月初一 <= 目标日期 < 下一年正月初一）
        2. 累加该农历年各月天数，定位到具体月日
        3. 计算干支信息

    异常:
        ValueError: 日期超出支持范围
    """
    if year < 1900 or year > 2100:
        raise ValueError(f"公历年份 {year} 不在支持范围内 (1900-2100)")

    target_date = date(year, month, day)

    # ---- 步骤1: 确定农历年份 ----
    # 查找目标日期落在哪个农历年
    lunar_year = year
    cny = get_lunar_new_year(lunar_year)

    if target_date < cny:
        # 目标日期在上一个农历年
        lunar_year = year - 1
        cny = get_lunar_new_year(lunar_year)
    else:
        # 检查是否在下一年
        next_cny = get_lunar_new_year(lunar_year + 1)
        if target_date >= next_cny:
            lunar_year = year + 1
            cny = next_cny

    # ---- 步骤2: 在农历年内定位到具体月日 ----
    leap_month, bitmask, _ = _get_lunar_data(lunar_year)
    days_since_cny = _days_between_dates(cny, target_date)  # 从正月初一开始的天数

    lunar_month = 1
    lunar_day = 1
    is_leap = False
    accumulated = 0

    for m in range(1, 13):
        # 正常月
        month_days = 30 if (bitmask & (1 << (m - 1))) else 29
        if days_since_cny < accumulated + month_days:
            lunar_month = m
            lunar_day = days_since_cny - accumulated + 1
            is_leap = False
            break
        accumulated += month_days

        # 闰月（如果有）
        if leap_month == m:
            leap_days = 30 if (bitmask & (1 << 12)) else 29
            if days_since_cny < accumulated + leap_days:
                lunar_month = m
                lunar_day = days_since_cny - accumulated + 1
                is_leap = True
                break
            accumulated += leap_days

    # ---- 步骤3: 计算干支信息 ----
    # 年柱: 以立春为界
    from .solar_terms import get_solar_term, get_current_solar_term

    # 获取立春日期以确定年柱
    try:
        lichun = get_solar_term(year, "立春")
        lichun_date = lichun.date() if isinstance(lichun, datetime) else lichun
        if target_date >= lichun_date:
            ganzhi_year_index = _compute_year_ganzhi_index(year)
        else:
            ganzhi_year_index = _compute_year_ganzhi_index(year - 1)
    except Exception:
        # fallback: use the traditional approximate method
        ganzhi_year_index = _compute_year_ganzhi_index(year)

    year_gan = _TIANGAN[ganzhi_year_index % 10]
    year_zhi = _DIZHI[ganzhi_year_index % 12]
    year_ganzhi = year_gan + year_zhi

    # 生肖
    animal = _SHENGXIAO[ganzhi_year_index % 12]

    # 日干支
    day_ganzhi_index = _compute_day_ganzhi_index(target_date)
    day_ganzhi = _SEXAGENARY[day_ganzhi_index]

    # 月干支（简化版，精确版请用 month_pillar 模块）
    # 这里调用 month_pillar 模块（如果可用）
    try:
        from .month_pillar import get_month_pillar
        from .solar_terms import get_solar_term
        # 找到当前所处的节
        # 函数 get_month_pillar 需要节气日期
        # 这里使用简化方法：基于节气的月干支
        prev_term, prev_date, next_term, next_date = get_current_solar_term(target_date)
        if isinstance(prev_date, datetime):
            prev_date_dt = prev_date
        else:
            prev_date_dt = datetime(prev_date.year, prev_date.month, prev_date.day)

        month_gan, month_zhi = get_month_pillar(year, prev_term)
        month_ganzhi = month_gan + month_zhi
    except Exception:
        month_ganzhi = ""

    # 节气信息
    try:
        prev_term, prev_date, next_term, next_date = get_current_solar_term(target_date)
        solar_term_info = {
            "prev_term": prev_term,
            "prev_term_date": prev_date,
            "next_term": next_term,
            "next_term_date": next_date,
        }
    except Exception:
        solar_term_info = {}

    return {
        "lunar_year": lunar_year,
        "lunar_month": lunar_month,
        "lunar_day": lunar_day,
        "is_leap": is_leap,
        "leap_month": leap_month,
        "year_ganzhi": year_ganzhi,
        "month_ganzhi": month_ganzhi,
        "day_ganzhi": day_ganzhi,
        "animal": animal,
        "solar_term_info": solar_term_info,
    }


def lunar_to_solar(year, month, day, leap=False):
    """
    农历转公历。

    参数:
        year: 农历年份
        month: 农历月份 (1-12)
        day: 农历日 (1-30)
        leap: 该月是否为闰月

    返回:
        dict: {"year": int, "month": int, "day": int}

    算法:
        1. 找到农历年正月初一的公历日期
        2. 累加从正月初一到目标月份的天数
        3. 得到公历日期

    异常:
        ValueError: 日期无效
    """
    if year < 1900 or year > 2100:
        raise ValueError(f"农历年份 {year} 不在支持范围内 (1900-2100)")

    leap_month, bitmask, _ = _get_lunar_data(year)

    # 验证闰月
    if leap and (leap_month == 0 or month != leap_month):
        raise ValueError(f"{year}年无闰{month}月 (闰月为{leap_month}月)")

    # 验证日期
    month_days = get_lunar_month_days(year, month, leap)
    if day < 1 or day > month_days:
        raise ValueError(f"{year}年{'闰' if leap else ''}{month}月没有第{day}天 (该月{month_days}天)")

    # 正月初一的公历日期
    cny = get_lunar_new_year(year)

    # 从正月初一累加到目标月
    accumulated = 0
    found = False

    for m in range(1, 13):
        # 正常月
        normal_days = 30 if (bitmask & (1 << (m - 1))) else 29
        if m == month and not leap:
            accumulated += (day - 1)
            found = True
            break
        accumulated += normal_days

        # 闰月
        if leap_month == m:
            leap_days = 30 if (bitmask & (1 << 12)) else 29
            if m == month and leap:
                accumulated += (day - 1)
                found = True
                break
            accumulated += leap_days

    if not found:
        raise ValueError(f"无法定位到{year}年{'闰' if leap else ''}{month}月{day}日")

    result_date = cny + timedelta(days=accumulated)
    return {"year": result_date.year, "month": result_date.month, "day": result_date.day}


def _compute_day_ganzhi_index(target_date):
    """
    计算指定日期的日干支序号 (0-59)。

    使用公历1900年1月1日作为基准日。
    基准日干支: 1900-01-01 为甲戌日 (序号10, 甲=0 戌=10, 满足 i%10=0, i%12=10 → i=10)

    参数:
        target_date: date 对象

    返回:
        int: 0-59, 对应 _SEXAGENARY 索引
    """
    # 基准: 1900-01-01 = 甲戌 (index 10 in 60-day cycle)
    # 甲戌: stem 甲=0, branch 戌=10
    # index: i%10=0, i%12=10 → i=10 (and i=10*6-... let's verify: 10%10=0✓, 10%12=10✓)
    base_date = date(1900, 1, 1)
    base_index = 10  # 甲戌

    delta_days = _days_between_dates(base_date, target_date)
    return (base_index + delta_days) % 60


def _compute_year_ganzhi_index(year):
    """
    计算年干支序号（以立春为界）。

    甲子年对应序号0, 乙丑为1, ..., 癸亥为59。

    已知: 2024年是甲辰年 (序号40: stem 甲=0, branch 辰=4)
    40 = a; a%10=0 → a=0,10,20,30,40,50; a%12=4 → a=4,16,28,40,52 → a=40

    参数:
        year: 公历年份（注意: 八字年柱以立春为界，此函数计算的是该公历年大部分时间对应的年柱）

    返回:
        int: 0-59
    """
    # 2024 对应甲辰年 (index 40)
    reference_year = 2024
    reference_index = 40  # 甲辰

    year_diff = year - reference_year
    return (reference_index + year_diff) % 60


def get_ganzhi_day(target_date):
    """
    获取指定日期的日干支字符串。

    参数:
        target_date: date 或 datetime 对象

    返回:
        str: 干支字符串, 如 "甲子"
    """
    if isinstance(target_date, datetime):
        d = target_date.date()
    else:
        d = target_date
    index = _compute_day_ganzhi_index(d)
    return _SEXAGENARY[index]


def get_ganzhi_year(year):
    """
    获取年干支。

    注意: 八字年柱以立春为界。此函数返回的是该公历年的"大致"年柱。
    对于立春前/后的精确判断，请使用 solar_terms 模块配合。

    参数:
        year: 公历年份

    返回:
        str: 干支字符串, 如 "甲辰"
    """
    index = _compute_year_ganzhi_index(year)
    return _SEXAGENARY[index]


def get_lunar_year_info(year):
    """
    获取指定农历年份的完整信息。

    参数:
        year: 农历年份

    返回:
        dict:
            {
                "year": int,
                "leap_month": int,
                "month_count": int,        # 总月数 (12 或 13)
                "total_days": int,
                "cny_date": date,          # 正月初一公历日期
                "months": list of dict,    # 每月信息
            }
    """
    leap_month, bitmask, offset = _get_lunar_data(year)
    cny = date(year, 1, 1) + timedelta(days=offset)
    months = get_lunar_year_months(year)
    total_days = get_lunar_year_days(year)

    return {
        "year": year,
        "leap_month": leap_month,
        "month_count": len(months),
        "total_days": total_days,
        "cny_date": cny,
        "months": months,
    }
