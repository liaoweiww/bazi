"""
公历农历互转模块 - Lunar-Solar Calendar Conversion

实现公历(Gregorian)与农历(Chinese Lunar Calendar)之间的双向转换。
基于1900-2100年的农历编码数据，使用查表法 + 天文补正。

农历数据编码格式：
  每年一条记录：(leap_month, big_month_bitmask, cny_offset)
  - leap_month: 闰月编号 (0=无闰月, 1-12=闰月跟在第几个月后面)
  - big_month_bitmask: 整数，12-13位
    bit 0 (LSB)  = 正月大小 (1=大月30天, 0=小月29天)
    bit 1        = 二月大小
    ...
    bit 11       = 十二月大小
    bit 12       = 闰月大小 (仅当 leap_month > 0 时有效)
    bit 13       = 第二个闰月大小 (极少见，如2033年?)
  - cny_offset: 春节(正月初一)距离公历1月1日的天数 (0-50)

算法参考：
  - 中国农历编算规则 (GB/T 33661-2017)
  - 香港天文台农历数据
  - 寿星万年历
  - 各开源农历库交叉验证

重要注意事项（八字排盘）：
  - 年柱以立春为界，不是农历正月初一
  - 月柱以节气(十二"节")为界，不是农历月份
  - 日柱以子时(23:00)为日分界
  - 本模块只负责日期转换，不处理时辰分界
"""

