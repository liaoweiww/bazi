"""
星座星盘文案生成引擎
====================
参考专业占星书籍（Stephen Arroyo, Sue Tompkins, Howard Sasportas等），
为星盘计算结果生成深度中文解读。
"""

import json
import os


class AstrologyTextEngine:
    def __init__(self, data_dir=None):
        if data_dir is None:
            data_dir = os.path.dirname(os.path.abspath(__file__))
        self.data_dir = data_dir
        self._signs = None
        self._houses = None
        self._aspects = None

    def _load_signs(self):
        if self._signs is None:
            with open(os.path.join(self.data_dir, "signs.json"), "r", encoding="utf-8") as f:
                self._signs = json.load(f)
        return self._signs

    def _load_houses(self):
        if self._houses is None:
            with open(os.path.join(self.data_dir, "houses.json"), "r", encoding="utf-8") as f:
                self._houses = json.load(f)
        return self._houses

    def _load_aspects(self):
        if self._aspects is None:
            with open(os.path.join(self.data_dir, "aspects.json"), "r", encoding="utf-8") as f:
                self._aspects = json.load(f)
        return self._aspects

    # =========================================================================
    # 主入口
    # =========================================================================

    def interpret_full_chart(self, chart_result):
        planets = chart_result.get("planets", [])
        aspects = chart_result.get("aspects", [])
        houses = chart_result.get("houses", [])
        analysis = chart_result.get("analysis", {})
        angles = chart_result.get("angles", {})
        name = chart_result.get("name", "")

        sun = self._find(planets, "太阳")
        moon = self._find(planets, "月亮")
        mercury = self._find(planets, "水星")
        venus = self._find(planets, "金星")
        mars = self._find(planets, "火星")
        jupiter = self._find(planets, "木星")
        saturn = self._find(planets, "土星")
        uranus = self._find(planets, "天王星")
        neptune = self._find(planets, "海王星")
        pluto = self._find(planets, "冥王星")

        greeting = f"{name}，以下是你的深度星盘全解析" if name else "以下是你的深度星盘全解析"

        return {
            "greeting": greeting,
            "personality": self._gen_personality(sun, moon, angles, analysis, asc_sign=angles.get("ascendant_sign","")),
            "love": self._gen_love(venus, mars, sun, moon, houses, aspects),
            "career": self._gen_career(angles, saturn, jupiter, houses, sun),
            "wealth": self._gen_wealth(venus, jupiter, houses, analysis),
            "planet_details": self._gen_planet_details(planets),
            "aspect_details": self._gen_aspect_details(aspects),
            "big_three_summary": self._gen_big_three_summary(sun, moon, angles),
            "summary": analysis.get("summary", ""),
        }

    def _find(self, planets, name_cn):
        for p in planets:
            if p["name_cn"] == name_cn:
                return p
        return None

