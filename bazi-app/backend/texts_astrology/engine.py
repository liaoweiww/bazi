    def _gen_planet_details(self, planets):
        out = []
        for p in planets:
            name = p["name_cn"]
            sign = p["sign"]
            house = p.get("house", "?")
            house_name = p.get("house_name", "")
            retro = "（逆行）" if p.get("is_retrograde") else ""
            desc = self._planet_sign_house_desc(name, sign, house, house_name, retro)
            if desc:
                out.append(desc)
        return out

    def _gen_aspect_details(self, aspects):
        out = []
        aspects_data = self._load_aspects()
        for a in aspects:
            atype = a.get("aspect_name_cn", "")
            sym = a.get("aspect_symbol", "")
            p1 = a.get("planet1", "")
            p2 = a.get("planet2", "")
            nature = a.get("nature", "")
            info = aspects_data.get(atype, {})
            base = info.get("general", f"{p1}与{p2}形成{atype}。")
            specific = self._aspect_specific(p1, p2, atype)
            advice = info.get("advice", "")
            out.append(f"【{p1} {sym} {p2} — {atype}（{nature}）】\n\n{base}\n\n{specific}\n\n{advice}")
        return out

